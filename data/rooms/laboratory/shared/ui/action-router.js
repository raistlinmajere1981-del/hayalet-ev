import { createLaboratoryUiActionHandlers } from "./action-router-actions.js";
import { createLaboratoryUiActionEventRuntime } from "./action-router-events.js";
export function createLaboratoryUiActionRouter(deps) {
  const {
    advanceStage,
    buildCurrentDraftPayload,
    buildCurrentEditRecipePatch,
    buildNestedPatch,
    closeSettingsOverlay,
    commitEditPatch,
    getActiveEditOutput,
    getCurrentEditDraft,
    getProfileTargetSummary,
    getProjectProfile,
    getSourceSnapshot,
    getToolRegistry,
    isAudioAnalysisFeature,
    openReport,
    openSettingsOverlay,
    persistDrafts,
    readFormValue,
    render,
    resetJourney,
    restartProcess,
    setActiveWorkbenchModule,
    setBlockingStatus,
    setResultStatus,
    sendMediaAction,
    sendSourceAction,
    setStage,
    state,
    syncDraftField,
    syncLocalEditField,
    text,
    toRecord,
    toggleCleanup,
    toggleEventLog,
    toggleWorkbenchModuleSelection
  } = deps;
  const { handleAction } = createLaboratoryUiActionHandlers({
    advanceStage,
    buildCurrentDraftPayload,
    buildCurrentEditRecipePatch,
    closeSettingsOverlay,
    getActiveEditOutput,
    getProfileTargetSummary,
    getSourceSnapshot,
    getToolRegistry,
    isAudioAnalysisFeature,
    openReport,
    openSettingsOverlay,
    persistDrafts,
    render,
    resetJourney,
    restartProcess,
    setActiveWorkbenchModule,
    setBlockingStatus,
    setResultStatus,
    sendMediaAction,
    sendSourceAction,
    state,
    syncDraftField,
    text,
    toggleEventLog,
    toggleWorkbenchModuleSelection
  });
  const laboratoryUiActionEventRuntime = createLaboratoryUiActionEventRuntime({
    buildNestedPatch,
    commitEditPatch,
    getCurrentEditDraft,
    getProjectProfile,
    handleAction,
    persistDrafts,
    readFormValue,
    render,
    sendMediaAction,
    sendSourceAction,
    setStage,
    state,
    syncDraftField,
    syncLocalEditField,
    toRecord,
    toggleCleanup
  });
  return {
    handleAction,
    handleChange: laboratoryUiActionEventRuntime.handleChange,
    handleClick: laboratoryUiActionEventRuntime.handleClick,
    handleInput: laboratoryUiActionEventRuntime.handleInput
  };
}
