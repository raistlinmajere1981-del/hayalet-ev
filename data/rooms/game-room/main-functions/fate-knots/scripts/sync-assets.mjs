import { copyFile, mkdir, readdir, readFile, rm, stat, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { basename, dirname, extname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export function normalizeRelativePath(value) {
  if (typeof value !== "string") {
    return null;
  }
  const normalized = value.replace(/\\/g, "/").trim();
  if (
    normalized === "" ||
    normalized.startsWith("/") ||
    /^[A-Za-z]:\//.test(normalized) ||
    normalized.startsWith("../") ||
    normalized.includes("/../")
  ) {
    return null;
  }
  const parts = normalized.split("/");
  if (parts.some((part) => part === "" || part === "." || part === "..")) {
    return null;
  }
  return parts.join("/");
}

function normalizeAbsolutePath(value) {
  return resolve(value).replace(/\\/g, "/");
}

function deriveId(fileName) {
  return basename(fileName, extname(fileName)).trim().toLowerCase();
}

async function readJsonFile(filePath) {
  return JSON.parse(await readFile(filePath, "utf8"));
}

function serializeModuleExport(name, value) {
  return `export const ${name} = ${JSON.stringify(value, null, 2)};\n`;
}

const GENERATED_MODULE_HEADER =
  "// Generated by rooms/game-room/main-functions/fate-knots/scripts/sync-assets.mjs. Do not edit manually.";

const RUNTIME_ASSET_SPLIT_MODULES = [
  {
    exportName: "fateKnotsRuntimeWorldAssetsManifest",
    modulePath: "./runtime-assets-world.module.js",
    includeAsset(asset) {
      return String(asset?.kind || "").startsWith("ui-") !== true;
    },
  },
  {
    exportName: "fateKnotsRuntimeUiAssetsManifest",
    modulePath: "./runtime-assets-ui.module.js",
    includeAsset(asset) {
      return String(asset?.kind || "").startsWith("ui-");
    },
  },
];

const RUNTIME_CONTENT_MODULES = [
  {
    exportName: "fateKnotsRuntimeAssetsManifest",
    modulePath: "./runtime-assets.module.js",
  },
  {
    exportName: "fateKnotsSelectionsManifest",
    modulePath: "./selections.module.js",
  },
  {
    exportName: "fateKnotsMapManifest",
    modulePath: "./map.module.js",
  },
  {
    exportName: "fateKnotsIntroScenarioManifest",
    modulePath: "./scenarios/intro.module.js",
  },
  {
    exportName: "fateKnotsCombatCardsManifest",
    modulePath: "./combat/cards.module.js",
  },
  {
    exportName: "fateKnotsCombatConfigManifest",
    modulePath: "./combat/config.module.js",
  },
];

function createGeneratedManifestModuleSource(exportName, value) {
  return [
    GENERATED_MODULE_HEADER,
    "",
    serializeModuleExport(exportName, value),
    `export default ${exportName};`,
    "",
  ].join("\n");
}

function createRuntimeContentModuleSource() {
  const importLines = RUNTIME_CONTENT_MODULES.map(function (entry) {
    return `import { ${entry.exportName} } from "${entry.modulePath}";`;
  });
  const exportNames = RUNTIME_CONTENT_MODULES.map(function (entry) {
    return entry.exportName;
  });

  return [
    GENERATED_MODULE_HEADER,
    "",
    ...importLines,
    "",
    `export { ${exportNames.join(", ")} };`,
    "",
    "export default {",
    ...exportNames.map((exportName) => `  ${exportName},`),
    "};",
    "",
  ].join("\n");
}

function createRuntimeAssetPartitionManifests(runtimeAssetsManifest) {
  return RUNTIME_ASSET_SPLIT_MODULES.map(function (entry) {
    return {
      ...entry,
      value: {
        ...runtimeAssetsManifest,
        assets: runtimeAssetsManifest.assets.filter(entry.includeAsset),
      },
    };
  });
}

function createRuntimeAssetsModuleSource(runtimeAssetsManifest, partitionManifests) {
  return [
    GENERATED_MODULE_HEADER,
    "",
    ...partitionManifests.map(function (entry) {
      return `import { ${entry.exportName} } from "${entry.modulePath}";`;
    }),
    "",
    "export const fateKnotsRuntimeAssetsManifest = {",
    `  version: ${JSON.stringify(runtimeAssetsManifest.version)},`,
    `  featureId: ${JSON.stringify(runtimeAssetsManifest.featureId)},`,
    `  generatedFrom: ${JSON.stringify(runtimeAssetsManifest.generatedFrom)},`,
    "  assets: [",
    ...partitionManifests.map(function (entry) {
      return `    ...${entry.exportName}.assets,`;
    }),
    "  ],",
    "};",
    "",
    "export default fateKnotsRuntimeAssetsManifest;",
    "",
  ].join("\n");
}

async function collectFiles(baseDir) {
  const entries = await readdir(baseDir, { withFileTypes: true });
  return entries
    .filter((entry) => entry.isFile())
    .map((entry) => entry.name)
    .sort((left, right) => left.localeCompare(right));
}

async function ensureParent(pathname) {
  await mkdir(dirname(pathname), { recursive: true });
}

async function writeGeneratedModule(outputPath, exportName, value) {
  await ensureParent(outputPath);
  await writeFile(outputPath, createGeneratedManifestModuleSource(exportName, value), "utf8");
}

async function removeStaleFiles(featureAssetsDir, expectedRelativePaths) {
  if (existsSync(featureAssetsDir) !== true) {
    return;
  }
  const stack = [featureAssetsDir];
  while (stack.length > 0) {
    const currentDir = stack.pop();
    const entries = await readdir(currentDir, { withFileTypes: true });
    for (const entry of entries) {
      const absolutePath = join(currentDir, entry.name);
      if (entry.isDirectory()) {
        stack.push(absolutePath);
        continue;
      }
      const rel = relative(featureAssetsDir, absolutePath).replace(/\\/g, "/");
      if (expectedRelativePaths.has(rel) !== true) {
        await rm(absolutePath, { force: true });
      }
    }
  }
}

export async function syncGameRoomFateKnotsAssets(options = {}) {
  const dryRun = options.dryRun === true;
  const scriptDir = dirname(fileURLToPath(import.meta.url));
  const featureRoot = options.featureRoot ? resolve(options.featureRoot) : resolve(scriptDir, "..");
  const projectRoot = options.projectRoot
    ? resolve(options.projectRoot)
    : resolve(featureRoot, "..", "..", "..", "..");
  const featureAssetsDir = options.featureAssetsDir
    ? resolve(options.featureAssetsDir)
    : join(featureRoot, "assets");
  const manifestPath = options.manifestPath
    ? resolve(options.manifestPath)
    : join(featureRoot, "data", "asset-import.manifest.json");
  const manifest = JSON.parse(await readFile(manifestPath, "utf8"));
  const entries = Array.isArray(manifest.entries) ? manifest.entries : [];
  const nextAssets = [];
  const expectedRelativePaths = new Set();

  for (const entry of entries) {
    const mode = entry && typeof entry === "object" ? entry.mode : "";
    const kind =
      entry && typeof entry === "object" && typeof entry.kind === "string" ? entry.kind.trim() : "";
    if (kind === "") {
      throw new Error("asset import entry.kind is required");
    }

    if (mode === "file") {
      const source = normalizeRelativePath(entry.source);
      const target = normalizeRelativePath(entry.target);
      if (source === null || target === null) {
        throw new Error(`unsafe file entry for kind ${kind}`);
      }
      const absoluteSource = join(projectRoot, source);
      const absoluteTarget = join(featureAssetsDir, target);
      const fileInfo = await stat(absoluteSource);
      expectedRelativePaths.add(target);
      nextAssets.push({
        id: deriveId(target),
        kind,
        sourcePath: source,
        sourceSize: fileInfo.size,
        src: `main-functions/fate-knots/assets/${target}`,
        uiSrc: `../main-functions/fate-knots/assets/${target}`,
      });
      if (dryRun !== true) {
        if (normalizeAbsolutePath(absoluteSource) !== normalizeAbsolutePath(absoluteTarget)) {
          await ensureParent(absoluteTarget);
          await copyFile(absoluteSource, absoluteTarget);
        }
      }
      continue;
    }

    if (mode === "directory") {
      const sourceDir = normalizeRelativePath(entry.sourceDir);
      const targetDir = normalizeRelativePath(entry.targetDir);
      if (sourceDir === null || targetDir === null) {
        throw new Error(`unsafe directory entry for kind ${kind}`);
      }
      const absoluteSourceDir = join(projectRoot, sourceDir);
      const fileNames = await collectFiles(absoluteSourceDir);
      for (const fileName of fileNames) {
        const relTarget = `${targetDir}/${fileName}`;
        const absoluteSource = join(absoluteSourceDir, fileName);
        const absoluteTarget = join(featureAssetsDir, relTarget);
        const fileInfo = await stat(absoluteSource);
        expectedRelativePaths.add(relTarget);
        nextAssets.push({
          id: deriveId(fileName),
          kind,
          sourcePath: `${sourceDir}/${fileName}`,
          sourceSize: fileInfo.size,
          src: `main-functions/fate-knots/assets/${relTarget}`,
          uiSrc: `../main-functions/fate-knots/assets/${relTarget}`,
        });
        if (dryRun !== true) {
          await ensureParent(absoluteTarget);
          await copyFile(absoluteSource, absoluteTarget);
        }
      }
      continue;
    }

    throw new Error(`unsupported asset import mode: ${String(mode)}`);
  }

  if (dryRun !== true) {
    await removeStaleFiles(featureAssetsDir, expectedRelativePaths);
    const outputPath = join(featureRoot, "data", "runtime-assets.manifest.json");
    const runtimeAssetsManifest = {
      version: 1,
      featureId: "fate-knots",
      generatedFrom: "data/asset-import.manifest.json",
      assets: nextAssets.sort((left, right) => {
        const byKind = left.kind.localeCompare(right.kind);
        return byKind !== 0 ? byKind : left.id.localeCompare(right.id);
      }),
    };
    await writeFile(outputPath, JSON.stringify(runtimeAssetsManifest, null, 2) + "\n", "utf8");

    const selectionsManifest = await readJsonFile(join(featureRoot, "data", "selections.manifest.json"));
    const mapManifest = await readJsonFile(join(featureRoot, "data", "map.manifest.json"));
    const introScenarioManifest = await readJsonFile(
      join(featureRoot, "data", "scenarios", "intro.manifest.json")
    );
    const combatCardsManifest = await readJsonFile(
      join(featureRoot, "data", "combat", "cards.manifest.json")
    );
    const combatConfigManifest = await readJsonFile(
      join(featureRoot, "data", "combat", "config.manifest.json")
    );

    const runtimeAssetPartitionManifests = createRuntimeAssetPartitionManifests(runtimeAssetsManifest);
    for (const partitionManifest of runtimeAssetPartitionManifests) {
      await writeGeneratedModule(
        join(featureRoot, "data", partitionManifest.modulePath.replace(/^\.\//, "")),
        partitionManifest.exportName,
        partitionManifest.value
      );
    }
    await ensureParent(join(featureRoot, "data", "runtime-assets.module.js"));
    await writeFile(
      join(featureRoot, "data", "runtime-assets.module.js"),
      createRuntimeAssetsModuleSource(runtimeAssetsManifest, runtimeAssetPartitionManifests),
      "utf8"
    );
    await writeGeneratedModule(
      join(featureRoot, "data", "selections.module.js"),
      "fateKnotsSelectionsManifest",
      selectionsManifest
    );
    await writeGeneratedModule(
      join(featureRoot, "data", "map.module.js"),
      "fateKnotsMapManifest",
      mapManifest
    );
    await writeGeneratedModule(
      join(featureRoot, "data", "scenarios", "intro.module.js"),
      "fateKnotsIntroScenarioManifest",
      introScenarioManifest
    );
    await writeGeneratedModule(
      join(featureRoot, "data", "combat", "cards.module.js"),
      "fateKnotsCombatCardsManifest",
      combatCardsManifest
    );
    await writeGeneratedModule(
      join(featureRoot, "data", "combat", "config.module.js"),
      "fateKnotsCombatConfigManifest",
      combatConfigManifest
    );

    const runtimeContentModulePath = join(featureRoot, "data", "runtime-content.module.js");
    const runtimeContentModuleSource = createRuntimeContentModuleSource();
    await writeFile(runtimeContentModulePath, runtimeContentModuleSource, "utf8");
  }

  return {
    copiedAssets: nextAssets.length,
    dryRun,
  };
}

export async function main(argv = process.argv.slice(2)) {
  const summary = await syncGameRoomFateKnotsAssets({
    dryRun: argv.includes("--dry-run"),
  });
  process.stdout.write(`${JSON.stringify(summary, null, 2)}\n`);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  main().catch((error) => {
    process.stderr.write(`${error instanceof Error ? error.stack ?? error.message : String(error)}\n`);
    process.exitCode = 1;
  });
}
