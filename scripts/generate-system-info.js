#!/usr/bin/env node
import { fileURLToPath } from "url";
import { dirname, join } from "path";
import { readFileSync, writeFileSync, existsSync } from "fs";
import { execSync } from "child_process";
import os from "os";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const PROJECT_ROOT = join(__dirname, "..");

function getNickname() {
  try {
    const settingsPath = join(PROJECT_ROOT, "config", "settings.json");
    if (!existsSync(settingsPath)) return "unknown";
    const settings = JSON.parse(readFileSync(settingsPath, "utf-8"));
    return settings?.user?.nickname || "unknown";
  } catch {
    return "unknown";
  }
}

function getPlatformInfo() {
  try {
    const platform = os.platform();
    const arch = os.arch();
    const release = os.release();
    let distro = "unknown";
    let kernel = release;

    if (platform === "linux") {
      try {
        const osRelease = readFileSync("/etc/os-release", "utf-8");
        const prettyName = osRelease.match(/^PRETTY_NAME="?([^"\n]+)"?/m);
        if (prettyName) distro = prettyName[1].trim();
      } catch {
        distro = "Linux";
      }
      try {
        kernel = execSync("uname -r", { encoding: "utf-8" }).trim();
      } catch {
        kernel = release;
      }
    } else if (platform === "darwin") {
      try {
        const swVers = execSync("sw_vers -productVersion", { encoding: "utf-8" }).trim();
        distro = `macOS ${swVers}`;
      } catch {
        distro = "macOS";
      }
    } else if (platform === "win32") {
      distro = `Windows ${release}`;
    }

    return { platform, arch, distro, kernel };
  } catch {
    return { platform: os.platform(), arch: os.arch(), distro: "unknown", kernel: "unknown" };
  }
}

function getCpuInfo() {
  try {
    const cpus = os.cpus();
    if (!cpus || cpus.length === 0) return { model: "unknown", cores: 0, threads: 0, speedMhz: 0 };

    const model = cpus[0].model.replace(/\s+/g, " ").trim();
    const threads = cpus.length;

    // Physical core count — best effort
    let physicalCores = threads;
    try {
      if (os.platform() === "linux") {
        const cpuinfo = readFileSync("/proc/cpuinfo", "utf-8");
        const coreIds = new Set();
        const matches = cpuinfo.matchAll(/^core id\s*:\s*(\d+)/gm);
        for (const m of matches) coreIds.add(m[1]);
        if (coreIds.size > 0) physicalCores = coreIds.size;
      } else if (os.platform() === "darwin") {
        const result = execSync("sysctl -n hw.physicalcpu", { encoding: "utf-8" }).trim();
        physicalCores = parseInt(result) || threads;
      }
    } catch {
      physicalCores = threads;
    }

    const speedMhz = cpus[0].speed;
    return { model, cores: physicalCores, threads, speedMhz };
  } catch {
    return { model: "unknown", cores: 0, threads: 0, speedMhz: 0 };
  }
}

function getRamInfo() {
  const totalBytes = os.totalmem();
  const freeBytes = os.freemem();
  const totalGb = (totalBytes / 1024 ** 3).toFixed(1);
  const freeGb = (freeBytes / 1024 ** 3).toFixed(1);
  return { totalGb, freeGb };
}

function getShellInfo() {
  try {
    const shell = process.env.SHELL || process.env.COMSPEC || "unknown";
    const term = process.env.TERM || process.env.TERM_PROGRAM || "unknown";
    const display = process.env.DISPLAY || process.env.WAYLAND_DISPLAY || "none";
    const desktop = process.env.XDG_CURRENT_DESKTOP || process.env.DESKTOP_SESSION || "unknown";
    return { shell, term, display, desktop };
  } catch {
    return { shell: "unknown", term: "unknown", display: "none", desktop: "unknown" };
  }
}

function getNodeInfo() {
  return {
    version: process.version,
    v8: process.versions.v8 || "unknown",
  };
}

function generateMarkdown() {
  const now = new Date().toISOString();
  const nickname = getNickname();
  const platform = getPlatformInfo();
  const cpu = getCpuInfo();
  const ram = getRamInfo();
  const shell = getShellInfo();
  const node = getNodeInfo();

  let md = "# 🖥️ System Information\n\n";
  md += "> **Generated:** " + now + "\n";
  md += "> **Auto-generated by:** `scripts/generate-system-info.js`\n\n";
  md += "---\n\n";

  md += "## User\n\n";
  md += "| Key | Value |\n";
  md += "|-----|-------|\n";
  md += "| **Nickname** | " + nickname + " |\n";
  md += "\n";

  md += "## Operating System\n\n";
  md += "| Key | Value |\n";
  md += "|-----|-------|\n";
  md += "| **Platform** | " + platform.platform + " |\n";
  md += "| **Distro** | " + platform.distro + " |\n";
  md += "| **Kernel** | " + platform.kernel + " |\n";
  md += "| **Architecture** | " + platform.arch + " |\n";
  md += "\n";

  md += "## CPU\n\n";
  md += "| Key | Value |\n";
  md += "|-----|-------|\n";
  md += "| **Model** | " + cpu.model + " |\n";
  md += "| **Physical Cores** | " + cpu.cores + " |\n";
  md += "| **Threads (Logical)** | " + cpu.threads + " |\n";
  md += "| **Base Speed** | " + cpu.speedMhz + " MHz |\n";
  md += "\n";

  md += "## Memory (RAM)\n\n";
  md += "| Key | Value |\n";
  md += "|-----|-------|\n";
  md += "| **Total** | " + ram.totalGb + " GB |\n";
  md += "| **Free (at build time)** | " + ram.freeGb + " GB |\n";
  md += "\n";

  md += "## Runtime\n\n";
  md += "| Key | Value |\n";
  md += "|-----|-------|\n";
  md += "| **Node.js** | " + node.version + " |\n";
  md += "| **V8 Engine** | " + node.v8 + " |\n";
  md += "\n";

  md += "## Environment\n\n";
  md += "| Key | Value |\n";
  md += "|-----|-------|\n";
  md += "| **Shell** | " + shell.shell + " |\n";
  md += "| **Terminal** | " + shell.term + " |\n";
  md += "| **Display** | " + shell.display + " |\n";
  md += "| **Desktop** | " + shell.desktop + " |\n";
  md += "\n";

  return { md, nickname, platform, cpu, ram };
}

function main() {
  const outputPath = join(PROJECT_ROOT, ".rovo", "_metadata", "SYSTEM-INFO.md");
  const { md, nickname, platform, cpu, ram } = generateMarkdown();

  writeFileSync(outputPath, md, "utf-8");
  console.log("✅ System info generated: " + outputPath);
  console.log("👤 Nickname: " + nickname);
  console.log("🐧 OS: " + platform.distro + " (" + platform.arch + ")");
  console.log("⚡ CPU: " + cpu.model + " — " + cpu.cores + "c/" + cpu.threads + "t");
  console.log("🧠 RAM: " + ram.totalGb + " GB total");
}

main();
