#!/usr/bin/env node
import { fileURLToPath } from "url";
import { dirname, join } from "path";
import { writeFileSync } from "fs";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const PROJECT_ROOT = join(__dirname, "..");

const CATEGORIES = {
  Filesystem: "hev_fs_*",
  Development: "hev_dev_*",
  Web: "hev_web_*",
  Workflow: "hev_run_*",
  Memory: "memory_*",
  "Electron/CDP": "hev_* (others)",
  "Tool Discovery": "hev_* (discovery)",
  Provider: "hev_* (provider)",
  Debug: "hev_* (debug)",
};

async function loadToolDefinitions() {
  // Bootstrap the unified registry and get all definitions
  const { registerAllTools } = await import(
    join(PROJECT_ROOT, "mcp-server", "core", "handlers", "index.ts")
  );
  const { getAllDefinitions } = await import(
    join(PROJECT_ROOT, "mcp-server", "core", "registry.ts")
  );
  const context = { PROJECT_ROOT, LOG_DIR: join(PROJECT_ROOT, "logs") };
  registerAllTools(context);
  return getAllDefinitions();
}

function inferCategory(tool) {
  const category = tool.metadata?.category;
  if (category) {
    const normalized = category.toLowerCase();
    if (normalized === "filesystem") return "Filesystem";
    if (normalized === "development") return "Development";
    if (normalized === "web") return "Web";
    if (normalized === "workflow") return "Workflow";
    if (normalized === "memory") return "Memory";
    if (normalized === "electron") return "Electron/CDP";
    if (normalized === "provider") return "Provider";
    if (normalized === "debug") return "Debug";
    if (normalized === "discovery") return "Tool Discovery";
  }

  const name = tool.name || "";
  if (name.startsWith("hev_fs_")) return "Filesystem";
  if (name.startsWith("hev_dev_")) return "Development";
  if (name.startsWith("hev_web_")) return "Web";
  if (name.startsWith("hev_run_")) return "Workflow";
  if (name.startsWith("memory_") || name.startsWith("database_")) return "Memory";
  if (name.includes("provider") || name.includes("validate_provider") || name.includes("inspect_provider")) {
    return "Provider";
  }
  if (name.includes("suggest_tool") || name.includes("tool_workflow")) {
    return "Tool Discovery";
  }
  return "Electron/CDP";
}

function normalizeTools(tools) {
  return tools
    .filter((tool) => tool && tool.name)
    .map((tool) => ({
      name: tool.name,
      description: tool.description || "",
      category: inferCategory(tool),
    }))
    .sort((a, b) => a.name.localeCompare(b.name));
}

async function generateMarkdown() {
  const tools = normalizeTools(await loadToolDefinitions());
  let md = "# 🔧 Complete Tool List\n\n";
  md += "> **Generated:** " + new Date().toISOString() + "\n";
  md += "> **Total Tools:** " + tools.length + "\n\n";
  md += "> **Auto-generated by:** `scripts/generate-tool-list.js`\n\n";
  md += "---\n\n";

  const grouped = {};
  tools.forEach((tool) => {
    if (!grouped[tool.category]) grouped[tool.category] = [];
    grouped[tool.category].push(tool);
  });

  for (const [category, categoryTools] of Object.entries(grouped)) {
    md += `## ${category} (${categoryTools.length} tools)\n\n`;

    md += "| Tool | Description |\n";
    md += "|------|-------------|\n";
    categoryTools.forEach((tool) => {
      md += `| \`${tool.name}\` | ${tool.description} |\n`;
    });

    md += "\n";

    md += "### Detailed Tools\n\n";
    categoryTools.forEach((tool) => {
      md += `#### \`${tool.name}\`\n\n`;
      md += `**Description:** ${tool.description}\n\n`;
      md += `**Category:** ${category}\n\n`;
      const prefix = CATEGORIES[category] || "hev_*";
      md += `**Prefix:** \`${prefix}\`\n\n`;
      md += "---\n\n";
    });
  }

  md += "## Usage Examples\n\n";
  md += "### List all tools\n```bash\nhev_list_tools()\n```\n\n";
  md +=
    '### Get tool schema\n```bash\nmcp__app__get_tool_schema({ tool_name: "hev_dev_typescript_dashboard" })\n```\n\n';

  return md;
}

async function main() {
  const outputPath = join(__dirname, "..", ".rovo", "_metadata", "TOOL-LIST.md");
  const markdown = await generateMarkdown();

  writeFileSync(outputPath, markdown, "utf-8");
  console.log("✅ Tool list generated: " + outputPath);
  const totalMatch = markdown.match(/\*\*Total Tools:\*\*\s+(\d+)/);
  if (totalMatch) {
    console.log("📊 Total tools: " + totalMatch[1]);
  }
}

main().catch((error) => {
  console.error("❌ Tool list generation failed:", error.message);
  process.exit(1);
});
