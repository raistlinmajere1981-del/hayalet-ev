#!/usr/bin/env node
import { fileURLToPath } from "url";
import { dirname, join } from "path";
import { readFileSync, writeFileSync, existsSync } from "fs";
import { execSync } from "child_process";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

function getPackageVersion() {
  try {
    const packageJson = JSON.parse(readFileSync(join(__dirname, "..", "package.json"), "utf-8"));
    return packageJson.version || "unknown";
  } catch {
    return "unknown";
  }
}

function getMcpServerVersion() {
  try {
    const readmePath = join(__dirname, "..", "mcp-server", "README.md");
    if (!existsSync(readmePath)) return "unknown";

    const readme = readFileSync(readmePath, "utf-8");
    const match = readme.match(/\*\*v([\d.]+)\*\*/);
    return match ? match[1] : "unknown";
  } catch {
    return "unknown";
  }
}

function getToolCount() {
  try {
    const toolListPath = join(__dirname, "..", ".rovo", "_metadata", "TOOL-LIST.md");
    if (!existsSync(toolListPath)) return "unknown";

    const toolList = readFileSync(toolListPath, "utf-8");
    const match = toolList.match(/\*\*Total Tools:\*\*\s+(\d+)/);
    return match ? match[1] : "unknown";
  } catch {
    return "unknown";
  }
}

function getGitInfo() {
  try {
    const branch = execSync("git rev-parse --abbrev-ref HEAD", {
      encoding: "utf-8",
      cwd: join(__dirname, ".."),
    }).trim();
    const commit = execSync("git rev-parse --short HEAD", {
      encoding: "utf-8",
      cwd: join(__dirname, ".."),
    }).trim();
    return { branch, commit };
  } catch {
    return { branch: "unknown", commit: "unknown" };
  }
}

function getNodeVersion() {
  try {
    return process.version;
  } catch {
    return "unknown";
  }
}

function generateMarkdown() {
  const now = new Date().toISOString();

  let md = "# 📦 Version Information\n\n";
  md += "> **Generated:** " + now + "\n";
  md += "> **Auto-generated by:** `scripts/generate-version-info.js`\n\n";
  md += "---\n\n";

  md += "## Project\n\n";
  md += "| Key | Value |\n";
  md += "|-----|-------|\n";
  md += "| **Name** | Hayalet-ev (Ghost House) |\n";
  md += "| **Version** | " + getPackageVersion() + " |\n";
  md += "| **Last Updated** | " + now.split("T")[0] + " |\n";

  const gitInfo = getGitInfo();
  md += "| **Git Branch** | " + gitInfo.branch + " |\n";
  md += "| **Git Commit** | " + gitInfo.commit + " |\n";
  md += "\n";

  md += "## Documentation\n\n";
  md += "| Key | Value |\n";
  md += "|-----|-------|\n";
  md += "| **Schema Version** | 2.0 |\n";
  md += "| **Last Generated** | " + now + " |\n";
  md += "\n";

  md += "## MCP Server\n\n";
  md += "| Key | Value |\n";
  md += "|-----|-------|\n";
  md += "| **Version** | " + getMcpServerVersion() + " |\n";
  md += "| **Total Tools** | " + getToolCount() + " |\n";
  md += "\n";

  md += "## Dependencies\n\n";
  md += "| Key | Value |\n";
  md += "|-----|-------|\n";
  md += "| **Electron** | 39+ |\n";
  md += "| **Node.js** | " + getNodeVersion() + " (ESM) |\n";
  md += "| **TypeScript** | 5.x (strict) |\n";
  md += "| **Vite** | 7.3 |\n";
  md += "\n";

  md += "## Atlas Orchestration\n\n";
  md += "| Key | Value |\n";
  md += "|-----|-------|\n";
  md += "| **Version** | 1.0 |\n";
  md += "| **Model** | glm-4.7-free |\n";
  md += "| **Status** | ✅ Production Ready |\n";
  md += "\n";

  return md;
}

function main() {
  const outputPath = join(__dirname, "..", ".rovo", "_metadata", "VERSION-INFO.md");
  const markdown = generateMarkdown();

  writeFileSync(outputPath, markdown, "utf-8");
  console.log("✅ Version info generated: " + outputPath);
  console.log("📦 Version: " + getPackageVersion());
  console.log("🔧 MCP Server: " + getMcpServerVersion());
  console.log("📊 Total Tools: " + getToolCount());
}

main();
