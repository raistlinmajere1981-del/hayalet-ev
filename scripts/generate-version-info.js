#!/usr/bin/env node
import { fileURLToPath } from "url";
import { dirname, join } from "path";
import { readFileSync, writeFileSync, existsSync } from "fs";
import { execSync } from "child_process";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const PROJECT_ROOT = join(__dirname, "..");

function getPackageVersion() {
  try {
    const packageJson = JSON.parse(readFileSync(join(PROJECT_ROOT, "package.json"), "utf-8"));
    return packageJson.version || "unknown";
  } catch {
    return "unknown";
  }
}

function getMcpServerVersion() {
  try {
    const changelogPath = join(PROJECT_ROOT, "src", "mcp-server", "CHANGELOG.md");
    if (existsSync(changelogPath)) {
      const changelog = readFileSync(changelogPath, "utf-8");
      const match = changelog.match(/##\s+\[(\d+\.\d+\.\d+)\]/);
      if (match) return match[1];
    }

    const packagePath = join(PROJECT_ROOT, "src", "mcp-server", "package.json");
    if (existsSync(packagePath)) {
      const pkg = JSON.parse(readFileSync(packagePath, "utf-8"));
      if (pkg.version) return pkg.version;
    }

    return "unknown";
  } catch (error) {
    console.warn("⚠️  MCP version detection failed:", error.message);
    return "unknown";
  }
}

async function getToolCountFromRegistry() {
  try {
    // Bootstrap the unified registry and get count
    const { registerAllTools } = await import(
      join(PROJECT_ROOT, "src", "mcp-server", "core", "handlers", "index.ts")
    );
    const { getToolCount: getCount } = await import(
      join(PROJECT_ROOT, "src", "mcp-server", "core", "registry.ts")
    );
    const context = { PROJECT_ROOT, LOG_DIR: join(PROJECT_ROOT, "logs") };
    registerAllTools(context);
    return String(getCount());
  } catch (error) {
    console.warn("⚠️  Tool registry read failed:", error.message);
    return null;
  }
}

function getToolCountFromToolList() {
  try {
    const toolListPath = join(PROJECT_ROOT, ".rovo", "_metadata", "TOOL-LIST.md");
    if (!existsSync(toolListPath)) return "unknown";

    const toolList = readFileSync(toolListPath, "utf-8");
    const match = toolList.match(/\*\*Total Tools:\*\*\s+(\d+)/);
    return match ? match[1] : "unknown";
  } catch {
    return "unknown";
  }
}

async function getToolCount() {
  const registryCount = await getToolCountFromRegistry();
  if (registryCount) return registryCount;
  return getToolCountFromToolList();
}

function getGitInfo() {
  try {
    const branch = execSync("git rev-parse --abbrev-ref HEAD", {
      encoding: "utf-8",
      cwd: PROJECT_ROOT,
    }).trim();
    const commit = execSync("git rev-parse --short HEAD", {
      encoding: "utf-8",
      cwd: PROJECT_ROOT,
    }).trim();
    return { branch, commit };
  } catch {
    return { branch: "unknown", commit: "unknown" };
  }
}

function getNodeVersion() {
  try {
    return process.version;
  } catch {
    return "unknown";
  }
}

async function generateMarkdown() {
  const now = new Date().toISOString();
  const toolCount = await getToolCount();

  let md = "# 📦 Version Information\n\n";
  md += "> **Generated:** " + now + "\n";
  md += "> **Auto-generated by:** `scripts/generate-version-info.js`\n\n";
  md += "---\n\n";

  md += "## Project\n\n";
  md += "| Key | Value |\n";
  md += "|-----|-------|\n";
  md += "| **Name** | Hayalet-ev (Ghost House) |\n";
  md += "| **Version** | " + getPackageVersion() + " |\n";
  md += "| **Last Updated** | " + now.split("T")[0] + " |\n";

  const gitInfo = getGitInfo();
  md += "| **Git Branch** | " + gitInfo.branch + " |\n";
  md += "| **Git Commit** | " + gitInfo.commit + " |\n";
  md += "\n";

  md += "## Documentation\n\n";
  md += "| Key | Value |\n";
  md += "|-----|-------|\n";
  md += "| **Schema Version** | 2.0 |\n";
  md += "| **Last Generated** | " + now + " |\n";
  md += "\n";

  md += "## MCP Server\n\n";
  md += "| Key | Value |\n";
  md += "|-----|-------|\n";
  md += "| **Version** | " + getMcpServerVersion() + " |\n";
  md += "| **Total Tools** | " + toolCount + " |\n";
  md += "\n";

  md += "## Dependencies\n\n";
  md += "| Key | Value |\n";
  md += "|-----|-------|\n";
  md += "| **Electron** | 39+ |\n";
  md += "| **Node.js** | " + getNodeVersion() + " (ESM) |\n";
  md += "| **TypeScript** | 5.x (strict) |\n";
  md += "| **Vite** | 7.3 |\n";
  md += "\n";

  md += "## Memory System\n\n";
  md += "| Key | Value |\n";
  md += "|-----|-------|\n";
  md += "| **Database** | SQLite (per-account) |\n";
  md += "| **Status** | Production Ready ✅ |\n";
  md += "| **Format** | data/{email}_{provider}/archive.db |\n";
  md += "| **Features** | Full-text search, Transaction support, WAL mode |\n";
  md += "| **Performance** | <10ms queries, Sync API |\n";
  md += "| **Last Updated** | " + now.split("T")[0] + " |\n";
  md += "\n";

  return md;
}

async function main() {
  const outputPath = join(PROJECT_ROOT, ".rovo", "_metadata", "VERSION-INFO.md");
  const markdown = await generateMarkdown();

  writeFileSync(outputPath, markdown, "utf-8");
  console.log("✅ Version info generated: " + outputPath);
  console.log("📦 Version: " + getPackageVersion());
  console.log("🔧 MCP Server: " + getMcpServerVersion());
  console.log(
    "📊 Total Tools: " + (markdown.match(/\*\*Total Tools\*\* \| (\d+) \|/)?.[1] || "unknown")
  );
}

main().catch((error) => {
  console.error("❌ Version info generation failed:", error.message);
  process.exit(1);
});
